def accuracy_definitions_markdown() -> str:
    return """<!-- TASK_A_REWRITTEN_ANALYSIS -->
## Accuracy Definitions

Main Result 表里有四个 behavior accuracy。它们都只关心 next-token 任务里“下一个 token 是 Dyck 括号”的位置；noise target 不进入这些 Dyck accuracy 的分母。

记 `pred_t = argmax(logits_t)`，`target_t = x_{t+1}`，`D = {t: target_t 是 open/close bracket}`，`correct_t = 1[pred_t = target_t]`。实现上 `D` 对应 label 表里的 `target_is_dyck_position=True`。

| metric | 分母 | 计算方法 | 含义 |
|---|---:|---|---|
| `Dyck acc` | training/eval batches 里的 `D` | `mean(correct_t)` | 模型在 Dyck target 上的原始 next-token accuracy。Main Result 表中这个值来自训练阶段保存的 eval metric；与 extra-probe 的 `all_dyck_targets model_acc` 定义相同，但采样 batch 可能不同。 |
| `oracle acc` | extra-probe sampled `D` | `mean(oracle_next_dyck_acc_t)` | 当前 stochastic Dyck generator 下的可预测上限。forced 位置 oracle=1，free 位置 oracle=0.5，所以它取决于 forced/free 的比例。 |
| `forced acc` | `D` 中 `forced_state != free` 的位置 | `mean(correct_t | forced)` | 当前 prefix 已经唯一决定下一个括号时，模型是否执行合法 Dyck 约束。`height<=0` 时必须 open；`remaining_opens<=0` 或 `remaining_dyck<=height` 时必须 close。 |
| `free acc` | `D` 中 `forced_state == free` 的位置 | `mean(correct_t | free)` | open 和 close 都合法、sampler 随机二选一时的模型 accuracy。这里 oracle baseline 是 0.5；接近 0.5 不表示模型没学会合法性，而是目标本身没有确定答案。 |

因此读 Main Result 时，核心不是单看 `Dyck acc` 高低，而是比较 `Dyck acc` 是否接近 `oracle acc`，以及失败主要落在 `forced acc` 还是 `free acc`。"""


def primary_results_markdown(summary: pd.DataFrame, oracle: pd.DataFrame) -> str:
    oracle_all = oracle[oracle["split"].eq("all_dyck_targets")].set_index("setting")
    forced = oracle[oracle["split"].eq("forced")].set_index("setting")
    free = oracle[oracle["split"].eq("free")].set_index("setting")
    rows = []
    for row in summary.itertuples(index=False):
        rows.append(
            {
                "setting": row.setting,
                "Dyck acc": row.dyck_accuracy,
                "oracle acc": oracle_all.loc[row.setting, "oracle_acc"],
                "forced acc": forced.loc[row.setting, "model_acc"],
                "free acc": free.loc[row.setting, "model_acc"],
                "best height R2": row.height_r2,
                "legal-next probe": row.legal_next_class_accuracy,
            }
        )
    table = pd.DataFrame(rows)
    return (
        "<!-- TASK_A_REWRITTEN_ANALYSIS -->\n"
        "## Main Result: Two Regimes After Adding `tiny_extreme_long`\n\n"
        "原先五个 settings 呈现出一个比较干净的模式：Dyck next-token accuracy 看起来只有大约 0.53-0.62，"
        "但 oracle forced/free split 显示它们几乎贴着当前 stochastic generator 的 oracle ceiling。"
        "也就是说，这五组的低 accuracy 主要来自 free step 的 50/50 随机性，而不是合法性约束失败。\n\n"
        "新加的 `tiny_extreme_long` 则是一个真正不同的 regime：它只有 20 个括号 token 混在 2000 长上下文里，"
        "hidden 里仍有可读 count signal（height R2 约 0.80，legal-next probe 约 0.97），但行为没有贴近 oracle。"
        "特别是 forced accuracy 只有约 0.26，free accuracy 近乎 0。"
        "这说明“上下文极长 + 有效监督极稀疏”会造成比 Markov free-step ceiling 更严重的输出失败。\n\n"
        f"{markdown_table(table, float_digits=3)}\n\n"
        "这张表的核心读法：`forced acc` 代表规则已决定下一步时模型能否执行 Dyck 约束；`free acc` 代表规则没有决定时模型能否猜中随机采样结果。"
        "除 `tiny_extreme_long` 外，free acc 稳定在 0.501 左右，正好说明这一部分没有可学习的确定目标；"
        "`tiny_extreme_long` 的 forced/free 都低，说明它不是 oracle ceiling 问题，而是稀疏信号下的行为读出失败。"
    )


