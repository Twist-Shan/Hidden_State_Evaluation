def update_code_cell(cell: dict) -> dict:
    if cell.get("cell_type") != "code":
        return cell
    source = "".join(cell.get("source", []))
    if source.lstrip().startswith("TASK_A_GROUPS = ["):
        cell = {**cell, "source": task_groups_code().splitlines(keepends=True)}
    cell["execution_count"] = None
    cell["outputs"] = []
    return cell


