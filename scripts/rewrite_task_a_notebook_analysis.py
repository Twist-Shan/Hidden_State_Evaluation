def markdown_table(df: pd.DataFrame, *, float_digits: int) -> str:
    rows = [list(df.columns)]
    for record in df.to_dict(orient="records"):
        rows.append([format_value(record[col], float_digits=float_digits) for col in df.columns])
    widths = [max(len(str(row[col])) for row in rows) for col in range(len(rows[0]))]
    header = "| " + " | ".join(str(value).ljust(widths[i]) for i, value in enumerate(rows[0])) + " |"
    sep = "| " + " | ".join("-" * widths[i] for i in range(len(widths))) + " |"
    body = ["| " + " | ".join(str(value).ljust(widths[i]) for i, value in enumerate(row)) + " |" for row in rows[1:]]
    return "\n".join([header, sep, *body])


def format_value(value, *, float_digits: int) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, float):
        if math.isnan(value):
            return "N/A"
        return f"{value:.{float_digits}f}"
    if hasattr(value, "item"):
        return format_value(value.item(), float_digits=float_digits)
    return str(value)


def value_or_nan(df: pd.DataFrame, index: str, column: str) -> float:
    if index not in df.index:
        return float("nan")
    return float(df.loc[index, column])


