ROOT = Path(__file__).resolve().parents[1]
SETTINGS = ["tiny_extreme_long", "clean_short", "noisy_short", "sparse_medium", "sparse_long", "extreme_long"]
MARKER = "TASK_A_AUTOGENERATED_RESULTS"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--notebook", default="notebooks/Dyck_Syn_to_Rea/Task_A_Length_Noise.ipynb")
    parser.add_argument("--fig-dir", default="figures/dyck_counter_task_a")
    parser.add_argument("--summary-path", default="results/dyck_counter_task_a_summary.csv")
    parser.add_argument("--projection-max-rows", type=int, default=7000)
    parser.add_argument("--projection-max-per-height", type=int, default=120)
    args = parser.parse_args()

    fig_dir = ROOT / args.fig_dir
    fig_dir.mkdir(parents=True, exist_ok=True)

    summary = collect_summary()
    summary_path = ROOT / args.summary_path
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(summary_path, index=False)

    layerwise = collect_layerwise(summary)
    overview_path = plot_overview(summary, layerwise, fig_dir)
    projection_path = plot_height_axis_projection(
        summary,
        fig_dir,
        max_rows=args.projection_max_rows,
        max_per_height=args.projection_max_per_height,
    )

    update_notebook(
        ROOT / args.notebook,
        summary,
        image_paths=[overview_path, projection_path],
        summary_path=summary_path,
    )
    print(f"wrote {summary_path}")
    print(f"wrote {overview_path}")
    print(f"wrote {projection_path}")
    print(f"updated {ROOT / args.notebook}")


def collect_summary() -> pd.DataFrame:
    rows = []
    for setting in SETTINGS:
        run_dir = ROOT / "results" / f"dyck_counter_task_a_{setting}" / "transformer_seed0"
        cfg_path = run_dir / "config.json"
        cfg = load_json(cfg_path) if cfg_path.exists() else {}
        task = cfg.get("task", {})
        metrics_path = run_dir / "metrics.json"
        metadata_path = run_dir / "hidden_states" / "final" / "metadata.json"
        probes_path = run_dir / "probes" / "layerwise_probe.csv"

        metrics = load_json(metrics_path).get("eval", {}) if metrics_path.exists() else {}
        train = load_json(metrics_path).get("train", {}) if metrics_path.exists() else {}
        metadata = load_json(metadata_path) if metadata_path.exists() else {}
        best = {}
        if probes_path.exists():
            probes = pd.read_csv(probes_path)
            if not probes.empty and "height_r2" in probes:
                best = probes.sort_values("height_r2", ascending=False).iloc[0].to_dict()

        height_r2 = as_float(best.get("height_r2"))
        dyck_accuracy = as_float(metrics.get("dyck_accuracy"))
        rows.append(
            {
                "setting": setting,
                "run_dir": relpath(run_dir),
                "metrics": metrics_path.exists(),
                "hidden": metadata_path.exists(),
                "probe": probes_path.exists(),
                "seq_len": as_int(task.get("seq_len")),
                "total_length": as_int(task.get("total_length")),
                "repeat_prob": as_float(task.get("repeat_prob")),
                "noise_vocab": as_int(task.get("num_noise_tokens")),
                "train_steps": as_int(cfg.get("training_steps") or last_value(train.get("step"))),
                "batch_size": as_int(cfg.get("batch_size")),
                "loss": as_float(metrics.get("loss")),
                "accuracy": as_float(metrics.get("accuracy")),
                "dyck_accuracy": dyck_accuracy,
                "hidden_rows": as_int(metadata.get("hidden_rows")),
                "extracted_examples": as_int(metadata.get("num_examples")),
                "best_layer": as_int(best.get("layer")),
                "height_r2": height_r2,
                "height_mae": as_float(best.get("height_mae")),
                "left_r2": as_float(best.get("left_r2")),
                "right_r2": as_float(best.get("right_r2")),
                "legal_next_class_accuracy": as_float(best.get("legal_next_class_accuracy")),
                "probe_gap": height_r2 - dyck_accuracy if pd.notna(height_r2) and pd.notna(dyck_accuracy) else np.nan,
            }
        )
    return pd.DataFrame(rows)


def collect_layerwise(summary: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for row in summary.itertuples(index=False):
        path = ROOT / row.run_dir / "probes" / "layerwise_probe.csv"
        if not path.exists():
            continue
        layerwise = pd.read_csv(path)
        layerwise.insert(0, "setting", row.setting)
        rows.append(layerwise)
    return pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()


def plot_overview(summary: pd.DataFrame, layerwise: pd.DataFrame, fig_dir: Path) -> Path:
    complete = summary.loc[summary["probe"].astype(bool)].copy()
    complete["setting"] = pd.Categorical(complete["setting"], categories=SETTINGS, ordered=True)
    complete = complete.sort_values("setting")

    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    x = np.arange(len(complete))

    ax = axes[0, 0]
    ax.plot(x, complete["dyck_accuracy"], marker="o", label="Dyck next-token acc", color="#2563eb")
    ax.plot(x, complete["height_r2"], marker="o", label="Best-layer height R2", color="#dc2626")
    ax.plot(x, complete["legal_next_class_accuracy"], marker="o", label="Legal-next probe acc", color="#059669")
    ax.set_xticks(x)
    ax.set_xticklabels(complete["setting"], rotation=35, ha="right")
    ax.set_ylim(0, 1.02)
    ax.set_title("Behavior vs linear count readout")
    ax.grid(alpha=0.22)
    ax.legend(frameon=False, fontsize=9)

    ax = axes[0, 1]
    colors = np.where(complete["probe_gap"] >= 0, "#7c3aed", "#d97706")
    ax.bar(x, complete["probe_gap"], color=colors, alpha=0.82)
    ax.axhline(0, color="black", lw=0.8)
    ax.set_xticks(x)
    ax.set_xticklabels(complete["setting"], rotation=35, ha="right")
    ax.set_title("Height R2 minus behavior accuracy")
    ax.set_ylabel("probe gap")
    ax.grid(axis="y", alpha=0.22)

    ax = axes[1, 0]
    if not layerwise.empty:
        heat = (
            layerwise.assign(setting=pd.Categorical(layerwise["setting"], SETTINGS, ordered=True))
            .pivot_table(index="setting", columns="layer", values="height_r2", aggfunc="mean", observed=False)
            .reindex(SETTINGS)
        )
        im = ax.imshow(heat.to_numpy(dtype=float), cmap="viridis", vmin=0, vmax=1, aspect="auto")
        ax.set_xticks(np.arange(len(heat.columns)))
        ax.set_xticklabels([str(c) for c in heat.columns])
        ax.set_yticks(np.arange(len(heat.index)))
        ax.set_yticklabels(heat.index)
        ax.set_title("Layerwise height R2")
        ax.set_xlabel("layer")
        for yi in range(heat.shape[0]):
            for xi in range(heat.shape[1]):
                value = heat.iloc[yi, xi]
                if pd.notna(value):
                    ax.text(xi, yi, f"{value:.2f}", ha="center", va="center", color="white", fontsize=8)
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    else:
        ax.axis("off")

    ax = axes[1, 1]
    sc = ax.scatter(
        complete["seq_len"],
        complete["height_r2"],
        c=complete["dyck_accuracy"],
        s=40 + complete["noise_vocab"].fillna(0).astype(float) * 2,
        cmap="plasma",
        vmin=0,
        vmax=1,
        edgecolors="black",
        linewidths=0.4,
    )
    label_offsets = {
        "tiny_extreme_long": (-92, 8),
        "extreme_long": (6, -16),
        "sparse_long": (6, 8),
    }
    for _, row in complete.iterrows():
        offset = label_offsets.get(row["setting"], (4, 3))
        ax.annotate(row["setting"], (row["seq_len"], row["height_r2"]), xytext=offset, textcoords="offset points", fontsize=8)
    ax.set_xscale("log")
    ax.set_ylim(0, 1.02)
    ax.set_xlabel("sequence length, log scale")
    ax.set_ylabel("best-layer height R2")
    ax.set_title("Length/noise sweep")
    ax.grid(alpha=0.22)
    cbar = fig.colorbar(sc, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label("Dyck accuracy")

    fig.tight_layout()
    out_path = fig_dir / "task_a_overview.png"
    fig.savefig(out_path, dpi=180, bbox_inches="tight")
    plt.close(fig)
    return out_path


def plot_height_axis_projection(summary: pd.DataFrame, fig_dir: Path, *, max_rows: int, max_per_height: int) -> Path:
    complete = summary.loc[summary["probe"].astype(bool)].copy()
    complete["setting"] = pd.Categorical(complete["setting"], categories=SETTINGS, ordered=True)
    complete = complete.sort_values("setting")

    fig, axes = plt.subplots(2, 3, figsize=(16, 9), sharex=False, sharey=False)
    axes = axes.ravel()
    projected = []
    for row in complete.itertuples(index=False):
        try:
            projected.append((row, project_run(row, max_rows=max_rows, max_per_height=max_per_height), None))
        except FileNotFoundError as exc:
            projected.append((row, None, exc))
    max_height = max((float(proj["height"].max()) for _, proj, exc in projected if proj is not None and exc is None), default=1.0)
    norm = plt.Normalize(vmin=0, vmax=max(1.0, max_height))
    last_scatter = None
    for ax, (row, proj, exc) in zip(axes, projected):
        if exc is not None:
            ax.text(0.5, 0.5, str(exc), ha="center", va="center", wrap=True)
            ax.set_axis_off()
            continue

        dyck = proj["is_dyck_position"].to_numpy(dtype=bool)
        for mask, label, alpha, size, marker in [
            (~dyck, "noise", 0.12, 5, "."),
            (dyck, "dyck", 0.35, 8, "o"),
        ]:
            if not mask.any():
                continue
            last_scatter = ax.scatter(
                proj.loc[mask, "height_axis"],
                proj.loc[mask, "residual_pc1"],
                c=proj.loc[mask, "height"],
                cmap="viridis",
                norm=norm,
                s=size,
                alpha=alpha,
                marker=marker,
                edgecolors="none",
                label=label,
            )
        centroids = proj.groupby("height", as_index=False)[["height_axis", "residual_pc1"]].mean()
        if len(centroids) > 1:
            ax.plot(centroids["height_axis"], centroids["residual_pc1"], color="black", lw=1.0, alpha=0.6)
        ax.set_title(f"{row.setting} | layer {int(row.best_layer)} | R2={row.height_r2:.2f}")
        ax.set_xlabel("height probe direction")
        ax.set_ylabel("residual PC1")
        ax.grid(alpha=0.18)
        ax.legend(frameon=False, fontsize=8, loc="best")

    for ax in axes[len(complete) :]:
        ax.set_axis_off()
    if last_scatter is not None:
        cbar = fig.colorbar(last_scatter, ax=axes.tolist(), fraction=0.025, pad=0.02)
        cbar.set_label("height")
    fig.suptitle("Best-layer hidden states projected onto height direction plus residual PC1", y=0.995)
    out_path = fig_dir / "task_a_height_axis_projection.png"
    fig.savefig(out_path, dpi=180, bbox_inches="tight")
    plt.close(fig)
    return out_path


def project_run(row, *, max_rows: int, max_per_height: int) -> pd.DataFrame:
    run_dir = ROOT / row.run_dir
    layer = int(row.best_layer)
    labels = pd.read_parquet(run_dir / "hidden_states" / "final" / "labels.parquet").reset_index(drop=True)
    idx = stratified_height_sample(labels, max_rows=max_rows, max_per_height=max_per_height)
    hidden = torch.load(run_dir / "hidden_states" / "final" / f"layer_{layer}.pt", map_location="cpu")
    direction = torch.load(run_dir / "probes" / "directions" / f"final_layer_{layer}_height.pt", map_location="cpu")

    X = hidden[idx].float().numpy()
    labels = labels.iloc[idx].reset_index(drop=True)
    w = np.asarray(direction, dtype=float).reshape(-1)
    w = w / (np.linalg.norm(w) + 1e-12)
    Xc = X - X.mean(axis=0, keepdims=True)
    height_axis = Xc @ w
    residual = Xc - height_axis[:, None] * w[None, :]
    if residual.shape[0] > 2:
        _, _, vt = np.linalg.svd(residual, full_matrices=False)
        residual_pc1 = residual @ vt[0]
    else:
        residual_pc1 = np.zeros(residual.shape[0])
    out = labels[["height", "is_dyck_position", "position", "dyck_seen"]].copy()
    out["height_axis"] = height_axis
    out["residual_pc1"] = residual_pc1
    del hidden, direction, X, residual
    gc.collect()
    return out


def stratified_height_sample(labels: pd.DataFrame, *, max_rows: int, max_per_height: int) -> np.ndarray:
    rng = np.random.default_rng(0)
    chosen = []
    for _, idx in labels.groupby("height").indices.items():
        idx = np.asarray(idx)
        take = min(len(idx), max_per_height)
        if take > 0:
            chosen.append(rng.choice(idx, size=take, replace=False))
    if not chosen:
        idx = np.arange(len(labels))
    else:
        idx = np.concatenate(chosen)
    if len(idx) > max_rows:
        idx = rng.choice(idx, size=max_rows, replace=False)
    return np.sort(idx)


def update_notebook(notebook_path: Path, summary: pd.DataFrame, *, image_paths: list[Path], summary_path: Path) -> None:
    nb = json.loads(notebook_path.read_text(encoding="utf-8"))
    cells = []
    skip_next_old_snapshot_code = False
    for cell in nb.get("cells", []):
        source = "".join(cell.get("source", []))
        if MARKER in source:
            continue
        if "## Current Results Snapshot" in source:
            skip_next_old_snapshot_code = True
            continue
        if skip_next_old_snapshot_code and "dyck_counter_task_a_summary.csv" in source:
            skip_next_old_snapshot_code = False
            continue
        skip_next_old_snapshot_code = False
        cells.append(cell)

    table = summary_markdown_table(summary)
    rel_summary = relpath(summary_path)
    image_markdown = "\n\n".join(f"![{path.stem}]({relpath(path, start=notebook_path.parent)})" for path in image_paths)
    cells.extend(
        [
            markdown_cell(
                f"<!-- {MARKER} -->\n"
                "## Task A Results and Visualizations\n\n"
                f"Generated from `{rel_summary}` after all five Transformer seed-0 runs completed.\n\n"
                f"{table}\n"
            ),
            markdown_cell(f"<!-- {MARKER} -->\n{image_markdown}\n"),
            code_cell(
                f"# {MARKER}\n"
                "summary_path = ROOT / 'results' / 'dyck_counter_task_a_summary.csv'\n"
                "summary = pd.read_csv(summary_path)\n"
                "display(summary)\n"
            ),
            markdown_cell(task_a_interpretation_markdown()),
            markdown_cell(task_a_probe_plan_markdown()),
        ]
    )
    nb["cells"] = cells
    notebook_path.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")


def summary_markdown_table(summary: pd.DataFrame) -> str:
    columns = [
        ("setting", "setting"),
        ("seq_len", "seq_len"),
        ("repeat_prob", "repeat"),
        ("noise_vocab", "noise"),
        ("batch_size", "batch"),
        ("dyck_accuracy", "dyck_acc"),
        ("height_r2", "height_R2"),
        ("probe_gap", "gap"),
        ("best_layer", "layer"),
        ("hidden_rows", "hidden_rows"),
    ]
    lines = ["| " + " | ".join(label for _, label in columns) + " |"]
    lines.append("|" + "|".join(["---"] * len(columns)) + "|")
    for _, row in summary.iterrows():
        values = [format_value(row.get(key)) for key, _ in columns]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def task_a_interpretation_markdown() -> str:
    return """<!-- TASK_A_AUTOGENERATED_RESULTS -->
## Task A 结果解读

这五个 seed-0 Transformer run 展示出一个比较稳定的现象：**线性可读的计数表征**和**精确 next-token 行为**之间存在明显分离。

第一，counter 信息确实存在于 hidden state 里。`clean_short` 的 best-layer `height_R2 = 0.966`；即使在最难的 `extreme_long` 设置下，best layer 仍然有 `height_R2 = 0.730`。而且 `left` / `right` probe 在 noisy/long 条件里通常比 `height` 更强，经常仍高于 `0.95`。所以模型并不是简单地“没有存住括号计数信息”。

第二，精确 Dyck next-token accuracy 明显低得多，大约在 `0.53-0.62`；但线性 `legal_next_class` probe 很高，范围是 `0.958-1.000`。这说明 hidden state 通常已经包含“open/close 是否 legal”的信息，但模型的精确下一个 bracket 预测并没有变成确定性。这里有一个关键 caveat：当前 Dyck 生成器本身是 Markov 随机生成；当 open 和 close 都合法时，下一个 bracket 是随机采样的。因此，在没有计算 generator 的 oracle/Bayes baseline 前，不能默认 raw `dyck_accuracy` 的上限应该是 1.0。

第三，随着任务加入 noise 或变长，最干净的 counter 表征从早期层转移到中间层。`clean_short` 在 layer 0 最好，而其他设置都在 layer 1 最好。Layer 2 往往仍保留很强的 legal-next 信息，但不是最干净的 height readout。这暗示中间 block 形成了比较显式的 counter，而最后一层可能更贴近 token prediction objective 和 noise/token-mixture 细节。

第四，sparsity 和 noise 会削弱 height readout，但不会抹掉它。`sparse_medium` 降到 `height_R2 = 0.780`，`sparse_long` 回升到 `0.848`，`extreme_long` 又降到 `0.730`。其中 medium/long 的非单调变化要谨慎看待，因为 extraction 样本数、batch size 和随机性都有差异；但大趋势很清楚：即使行为维持在随机 next-token baseline 附近，counter 仍然线性可读。

所以当前主要解释是：**Task A 已经支持 representation-behavior gap，但 behavior 端需要更合理的 baseline。** 下一步 probes 要判断这个 gap 到底意味着“模型有 counter 但没有用它”，还是“模型有 counter，而且行为已经接近随机生成器的 Bayes-optimal 上限”。
"""


def task_a_probe_plan_markdown() -> str:
    return """<!-- TASK_A_AUTOGENERATED_RESULTS -->
## 下一步需要补的 probes

**1. Oracle baseline 和 forced/free next-token split。**  
在当前 Dyck Markov 生成器下计算 Bayes-optimal next-token accuracy。把 Dyck target 分成 `forced_open`、`forced_close` 和 `ambiguous_open_or_close` 三类。如果模型在 forced state 上准确率很高，而在 ambiguous state 上接近 0.5，那么 raw `dyck_accuracy` 低主要是 generator entropy，不是行为失败。

**2. Output-head 是否真的使用 counter。**  
检查 height/left/right 方向是否真的驱动 open-vs-close logits。具体做法是看 hidden 在 height 方向上的投影和 `(logit_open - logit_close)` 的相关性，并比较 height probe vector 与 unembedding difference vector 的夹角/余弦相似度。这可以区分“counter 被 LM head 使用”和“counter 只是 hidden state 里可读但不参与输出”。

**3. Causal height-direction intervention。**  
沿 learned height direction 移动 hidden state，再只跑 output head：提高 decoded height 是否会让 `close` logit 更高？降低 decoded height 是否会让 `open` logit 更高？这是验证 counter 是否被因果使用的最强检查。

**4. Cross-condition probe transfer。**  
在一个 condition 上训练 height/legal-next probe，然后拿到其他 condition 上测试。比如在 `clean_short` 上训练，在 `sparse_long` / `extreme_long` 上测试。这样可以判断不同设置是否共享同一个 counter geometry，还是每个设置都学到了各自的相关读出。

**5. Noise-schedule probes。**  
对 noisy/sparse 设置补 `is_next_dyck_token`、`distance_to_next_dyck`、`next_token_type` 等标签。当前 all-token accuracy 低，一部分原因是模型还要判断下一个 token 是 noise 还是 bracket。这类 probe 可以把 bracket-count 能力和 planted-position/noise 预测能力拆开。

**6. 按 height / position 分桶的 diagnostics。**  
把 probe error 和 model accuracy 按真实 `height`、`dyck_seen`、sequence position 分桶画出来。这样可以看 failure 是否集中在高 depth、接近结尾的 remaining-open constraint 区域，或长 noise gap 后的位置。

优先级建议：先做 **oracle forced/free split**，再做 **output-head use**，最后做 **causal height intervention**。这三个 probe 最直接回答当前结果里的核心歧义。
"""


def markdown_cell(source: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": source.splitlines(keepends=True)}


def code_cell(source: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": source.splitlines(keepends=True)}


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def relpath(path: Path, start: Path | None = None) -> str:
    start = ROOT if start is None else start
    return os.path.relpath(path.resolve(), start.resolve())


def last_value(values) -> float | None:
    if isinstance(values, list) and values:
        return values[-1]
    return None


def as_int(value) -> int | float:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return np.nan
    return int(value)


def as_float(value) -> float:
    if value is None:
        return np.nan
    return float(value)


def format_value(value) -> str:
    if value is None or pd.isna(value):
        return ""
    if isinstance(value, (bool, np.bool_)):
        return str(bool(value))
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        if abs(float(value)) >= 1000:
            return str(int(round(float(value))))
        return f"{float(value):.3f}"
    return str(value)


